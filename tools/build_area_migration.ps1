# Rebuilds the Greece area migration from Natural Earth.
#
#   1. Download ne_10m_admin_0_countries_grc.geojson (public domain) from
#      https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
#   2. ./tools/build_area_migration.ps1 -NaturalEarthFile <path to that file>
#
# Only change this before 0002 has been applied anywhere; afterwards add a new migration instead.
param(
    [Parameter(Mandatory)] [string] $NaturalEarthFile
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$tmp = Join-Path ([IO.Path]::GetTempPath()) "greece.geojson"

python -I (Join-Path $PSScriptRoot 'extract_greece.py') $NaturalEarthFile $tmp
if ($LASTEXITCODE -ne 0) { throw "extract_greece.py failed" }

$geojson = (Get-Content $tmp -Raw).Trim()
if ($geojson.Contains("'")) { throw "Unexpected quote in GeoJSON" }

$template = Get-Content (Join-Path $PSScriptRoot '0002_areas_of_interest.template.sql') -Raw
$sql = $template.Replace('{{GREECE_GEOJSON}}', $geojson).Replace(
    "-- Generated by tools/build_area_migration.ps1; edit the template, not the output.",
    "-- GENERATED by tools/build_area_migration.ps1 from tools/0002_areas_of_interest.template.sql. Do not edit.")

$out = Join-Path $root 'src/PyroLens.Infrastructure/Persistence/Migrations/0002_areas_of_interest.sql'
[IO.File]::WriteAllText($out, $sql, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $out ($([math]::Round((Get-Item $out).Length / 1KB)) KB)"
