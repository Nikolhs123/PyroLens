-- Fire detections from FIRMS and the incidents they are grouped into.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE incidents (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status             text NOT NULL DEFAULT 'detected'
                       CHECK (status IN ('detected', 'confirmed', 'active', 'contained', 'closed')),
    centroid           geometry(Point, 4326) NOT NULL,
    -- Convex hull of the detections: a point, a line or a polygon depending on their count.
    footprint          geometry(Geometry, 4326),
    first_detected_at  timestamptz NOT NULL,
    last_detected_at   timestamptz NOT NULL,
    detection_count    integer NOT NULL CHECK (detection_count > 0),
    max_frp_mw         double precision,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_incidents_centroid ON incidents USING gist (centroid);
CREATE INDEX ix_incidents_status_last_detected ON incidents (status, last_detected_at DESC);

CREATE TABLE fire_detections (
    id                 bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source             text NOT NULL,          -- FIRMS product, e.g. VIIRS_SNPP_NRT
    instrument         text NOT NULL CHECK (instrument IN ('MODIS', 'VIIRS')),
    satellite          text NOT NULL,
    latitude           double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude          double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    location           geometry(Point, 4326)
                       GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED,
    acquired_at        timestamptz NOT NULL,
    confidence_raw     text NOT NULL,
    confidence_class   text CHECK (confidence_class IN ('low', 'nominal', 'high')),  -- VIIRS
    confidence_pct     smallint CHECK (confidence_pct BETWEEN 0 AND 100),           -- MODIS
    brightness_k       double precision,
    frp_mw             double precision,
    is_daytime         boolean,
    likely_industrial  boolean NOT NULL DEFAULT false,
    incident_id        bigint REFERENCES incidents (id),
    ingested_at        timestamptz NOT NULL DEFAULT now(),

    -- The same pixel from the same product is stored once, however often it is fetched.
    CONSTRAINT uq_fire_detections_natural_key UNIQUE (source, acquired_at, latitude, longitude),
    CONSTRAINT ck_fire_detections_confidence CHECK (
        (instrument = 'VIIRS' AND confidence_class IS NOT NULL) OR
        (instrument = 'MODIS' AND confidence_pct IS NOT NULL))
);

CREATE INDEX ix_fire_detections_location ON fire_detections USING gist (location);
CREATE INDEX ix_fire_detections_location_geog ON fire_detections USING gist ((location::geography));
CREATE INDEX ix_fire_detections_acquired_at ON fire_detections (acquired_at DESC);
CREATE INDEX ix_fire_detections_incident ON fire_detections (incident_id);
CREATE INDEX ix_fire_detections_unassigned ON fire_detections (acquired_at)
    WHERE incident_id IS NULL AND NOT likely_industrial;
